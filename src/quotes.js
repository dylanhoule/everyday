// Index of the quote for day number n (days since 2000-01-01): a seeded shuffle per
// 100-day cycle, so each cycle shows every quote once, in a new order.
export function quoteIndex(n) {
  const len = QUOTES.length;
  let seed = Math.floor(n / len) + 1;
  const rand = () => (seed = (seed * 1664525 + 1013904223) % 4294967296) / 4294967296;
  const order = QUOTES.map((_, i) => i);
  for (let i = len - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [order[i], order[j]] = [order[j], order[i]];
  }
  return order[n % len];
}

export const quoteFor = (today) => QUOTES[quoteIndex(daysBetween('2000-01-01', today))];
